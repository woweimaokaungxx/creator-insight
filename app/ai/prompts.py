    "   - 0~0.5：补充性/背景性/举例性观点\n"
    "6. confidence（0-1）：博主表达该观点时的肯定程度（语气词+论据充实度判断），"
    "不是你对观点的认同度。\n"
    "7. 每个 Claim 补充：\n"
    "   - topic：观点所属主题（如\"黄金\"\"美联储\"\"A股\"\"宏观\"），无则 \"general\"\n"
